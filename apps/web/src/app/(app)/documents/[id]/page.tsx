'use client';

import Alert from '@mui/material/Alert';
import Box from '@mui/material/Box';
import Button from '@mui/material/Button';
import CircularProgress from '@mui/material/CircularProgress';
import Stack from '@mui/material/Stack';
import Typography from '@mui/material/Typography';
import Link from 'next/link';
import { useParams } from 'next/navigation';
import { useEffect, useState } from 'react';
import { ForbiddenState } from '@/components/feedback/ForbiddenState';
import { ApiError } from '@/lib/api/client';
import {
  downloadGeneratedDocument,
  formatDocumentDateTime,
  formatDocumentType,
  getDocument,
  getDocumentStudentDisplayName,
  type GeneratedDocument,
} from '@/lib/documents/documents-client';

export default function DocumentDetailPage() {
  const params = useParams<{ id: string }>();
  const documentId = params.id;
  const [document, setDocument] = useState<GeneratedDocument | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [isDownloading, setIsDownloading] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [downloadError, setDownloadError] = useState<string | null>(null);
  const [isForbidden, setIsForbidden] = useState(false);

  useEffect(() => {
    let cancelled = false;

    async function loadDocument(): Promise<void> {
      setIsLoading(true);
      setErrorMessage(null);
      setIsForbidden(false);

      try {
        const loaded = await getDocument(documentId);
        if (!cancelled) {
          setDocument(loaded);
        }
      } catch (error) {
        if (cancelled) {
          return;
        }
        if (error instanceof ApiError && error.statusCode === 403) {
          setIsForbidden(true);
        } else {
          setErrorMessage(error instanceof Error ? error.message : 'Failed to load document');
        }
      } finally {
        if (!cancelled) {
          setIsLoading(false);
        }
      }
    }

    void loadDocument();

    return () => {
      cancelled = true;
    };
  }, [documentId]);

  async function handleDownload(): Promise<void> {
    setIsDownloading(true);
    setDownloadError(null);

    try {
      const blob = await downloadGeneratedDocument(documentId);
      const objectUrl = URL.createObjectURL(blob);
      const anchor = window.document.createElement('a');
      anchor.href = objectUrl;
      anchor.download = document?.file?.originalName ?? 'document.pdf';
      anchor.click();
      URL.revokeObjectURL(objectUrl);
    } catch (error) {
      if (error instanceof ApiError && error.statusCode === 403) {
        setIsForbidden(true);
      } else {
        setDownloadError(error instanceof Error ? error.message : 'Failed to download document');
      }
    } finally {
      setIsDownloading(false);
    }
  }

  if (isForbidden) {
    return <ForbiddenState />;
  }

  return (
    <Stack spacing={3}>
      <Stack direction={{ xs: 'column', sm: 'row' }} justifyContent="space-between" spacing={2}>
        <Box>
          <Typography variant="h4" component="h1">
            Generated document
          </Typography>
          <Typography color="text.secondary">
            Review metadata and download the generated PDF securely.
          </Typography>
        </Box>
        <Button component={Link} href="/documents" variant="outlined">
          Back to documents
        </Button>
      </Stack>

      {isLoading ? (
        <Box sx={{ display: 'flex', justifyContent: 'center', py: 6 }}>
          <CircularProgress aria-label="Loading document" />
        </Box>
      ) : null}

      {errorMessage ? <Alert severity="error">{errorMessage}</Alert> : null}
      {downloadError ? <Alert severity="error">{downloadError}</Alert> : null}

      {!isLoading && document ? (
        <Stack spacing={2} maxWidth={640}>
          <Typography>
            <strong>Type:</strong> {formatDocumentType(document.documentType)}
          </Typography>
          <Typography>
            <strong>Student:</strong>{' '}
            {document.student
              ? `${getDocumentStudentDisplayName(document.student)} (${document.student.studentCode})`
              : '—'}
          </Typography>
          <Typography>
            <strong>Generated:</strong> {formatDocumentDateTime(document.createdAt)}
          </Typography>
          <Typography>
            <strong>Generated by:</strong> {document.generatedBy?.email ?? '—'}
          </Typography>
          <Typography>
            <strong>Status:</strong> {document.status}
          </Typography>
          <Typography>
            <strong>File:</strong> {document.file?.originalName ?? '—'}
          </Typography>

          <Button variant="contained" onClick={() => void handleDownload()} disabled={isDownloading}>
            {isDownloading ? 'Downloading…' : 'Download PDF'}
          </Button>
        </Stack>
      ) : null}
    </Stack>
  );
}
