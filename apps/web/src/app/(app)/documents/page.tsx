'use client';

import Alert from '@mui/material/Alert';
import Box from '@mui/material/Box';
import Button from '@mui/material/Button';
import CircularProgress from '@mui/material/CircularProgress';
import Stack from '@mui/material/Stack';
import Table from '@mui/material/Table';
import TableBody from '@mui/material/TableBody';
import TableCell from '@mui/material/TableCell';
import TableHead from '@mui/material/TableHead';
import TableRow from '@mui/material/TableRow';
import Typography from '@mui/material/Typography';
import Link from 'next/link';
import { useEffect, useState } from 'react';
import { ForbiddenState } from '@/components/feedback/ForbiddenState';
import { ApiError } from '@/lib/api/client';
import {
  formatDocumentDateTime,
  formatDocumentType,
  getDocumentStudentDisplayName,
  listDocuments,
  type GeneratedDocument,
} from '@/lib/documents/documents-client';

export default function DocumentsPage() {
  const [documents, setDocuments] = useState<GeneratedDocument[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [isForbidden, setIsForbidden] = useState(false);

  useEffect(() => {
    let cancelled = false;

    async function loadDocuments(): Promise<void> {
      setIsLoading(true);
      setErrorMessage(null);
      setIsForbidden(false);

      try {
        const response = await listDocuments({ page: 1, pageSize: 25 });
        if (!cancelled) {
          setDocuments(response.data);
        }
      } catch (error) {
        if (cancelled) {
          return;
        }
        if (error instanceof ApiError && error.statusCode === 403) {
          setIsForbidden(true);
        } else {
          setErrorMessage(error instanceof Error ? error.message : 'Failed to load documents');
        }
      } finally {
        if (!cancelled) {
          setIsLoading(false);
        }
      }
    }

    void loadDocuments();

    return () => {
      cancelled = true;
    };
  }, []);

  if (isForbidden) {
    return <ForbiddenState />;
  }

  return (
    <Stack spacing={3}>
      <Stack direction={{ xs: 'column', sm: 'row' }} justifyContent="space-between" spacing={2}>
        <Box>
          <Typography variant="h4" component="h1">
            Documents
          </Typography>
          <Typography color="text.secondary">
            View generated certificates and official documents for your organization.
          </Typography>
        </Box>
        <Button component={Link} href="/documents/generate" variant="contained">
          Generate document
        </Button>
      </Stack>

      {isLoading ? (
        <Box sx={{ display: 'flex', justifyContent: 'center', py: 6 }}>
          <CircularProgress aria-label="Loading documents" />
        </Box>
      ) : null}

      {errorMessage ? <Alert severity="error">{errorMessage}</Alert> : null}

      {!isLoading && documents.length === 0 ? (
        <Alert severity="info">No generated documents yet. Create your first bonafide certificate.</Alert>
      ) : null}

      {!isLoading && documents.length > 0 ? (
        <Box sx={{ overflowX: 'auto' }}>
          <Table>
            <TableHead>
              <TableRow>
                <TableCell>Document type</TableCell>
                <TableCell>Student</TableCell>
                <TableCell>Generated</TableCell>
                <TableCell>Generated by</TableCell>
                <TableCell>Status</TableCell>
                <TableCell align="right">Actions</TableCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {documents.map((document) => (
                <TableRow key={document.id}>
                  <TableCell>{formatDocumentType(document.documentType)}</TableCell>
                  <TableCell>
                    {document.student
                      ? `${getDocumentStudentDisplayName(document.student)} (${document.student.studentCode})`
                      : '—'}
                  </TableCell>
                  <TableCell>{formatDocumentDateTime(document.createdAt)}</TableCell>
                  <TableCell>{document.generatedBy?.email ?? '—'}</TableCell>
                  <TableCell>{document.status}</TableCell>
                  <TableCell align="right">
                    <Button component={Link} href={`/documents/${document.id}`} size="small">
                      View
                    </Button>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </Box>
      ) : null}
    </Stack>
  );
}
