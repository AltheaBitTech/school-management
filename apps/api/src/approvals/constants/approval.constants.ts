export const DEFAULT_LEAVE_APPROVAL_WORKFLOW_CODE = 'LEAVE_APPROVAL';

export const TERMINAL_APPROVAL_STATUSES = [
  ApprovalRequestStatus.APPROVED,
  ApprovalRequestStatus.REJECTED,
  ApprovalRequestStatus.CANCELLED,
] as const;

export function isTerminalApprovalStatus(status: ApprovalRequestStatus): boolean {
  return TERMINAL_APPROVAL_STATUSES.includes(status as (typeof TERMINAL_APPROVAL_STATUSES)[number]);
}
